"""Export the manuscript seed-2 comparison table from the verified reanalysis."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
METRICS = [
    ("tilt_p95_deg", r"Tilt P95 (\si{\degree})"),
    ("command_demeaned_combined_tilt_rms_deg", r"Command-demeaned tilt RMS (\si{\degree})"),
    ("combined_angular_rate_rms_rad_s", r"Roll--pitch rate RMS (rad/s)"),
    ("target_q_rate_rms_rad_s", r"Joint target-rate RMS (rad/s)"),
    ("joint_tau_est_rms_Nm", r"Estimated joint torque RMS (N\,m)"),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "analysis/hardware_normal_motion_20261031/normal_motion_reanalysis.json")
    parser.add_argument("--output", type=Path, default=ROOT / "res/seed2_prefall_comparison_table.tex")
    parser.add_argument("--source-data", type=Path, default=ROOT / "res/source_data/seed2_prefall_comparison")
    args = parser.parse_args()
    report = json.loads(args.input.read_text(encoding="utf-8"))
    primary = report.get("primary") or next(r for r in report["results"]
                   if r["end_time_exclusive_s"] == 40.0 and r["mode"] == "matched_commands")
    assert all(report["configuration_checks"].values())
    assert len(primary["command_bins"]) > 0
    assert abs(primary["effective_exposure_s"][0] - primary["effective_exposure_s"][1]) < 1e-8
    lines = [
        "% Generated by scripts/build_seed2_prefall_table.py; definitions are in the main text.",
        r"\begin{table}[htbp]",
        r"\caption{Seed-2 hardware comparison during regular locomotion.}",
        r"\label{tab:seed2-prefall-comparison}",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.08}",
        r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}>{\raggedright\arraybackslash}p{0.48\columnwidth}rrr@{}}",
        r"\toprule",
        r"Metric & Proposed & \shortstack[r]{Velocity-\\regularized} & \shortstack[r]{Reduction\\(\%)} \\",
        r"\midrule",
    ]
    for key, label in METRICS:
        reduction = 100 * (1 - primary["static"][key] / primary["smooth"][key])
        lines.append(f"{label} & {primary['static'][key]:.3f} & {primary['smooth'][key]:.3f} & {reduction:.1f} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular*}", r"\end{table}", ""]
    args.output.write_text("\n".join(lines), encoding="utf-8")
    args.source_data.mkdir(parents=True, exist_ok=True)
    with (args.source_data / "table_values.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["metric", "definition", "shifted", "smooth", "smooth_relative_change_pct", "shifted_reduction_vs_smooth_pct"])
        for key, _ in METRICS:
            writer.writerow([key, report["metric_definitions"][key], primary["static"][key],
                             primary["smooth"][key], primary["smooth_relative_change_pct"][key],
                             100 * (1 - primary["static"][key] / primary["smooth"][key])])
    (args.source_data / "selection.json").write_text(json.dumps({
        "analysis_report": str(args.input),
        "sessions": report["sessions"],
        "configuration_checks": report["configuration_checks"],
        "analysis_schema": report.get("schema", "legacy-prefall"),
        "source_files": report.get("source_files", []),
        "event_selection": report.get("selection"),
        "excluded_windows_s": primary.get("excluded_windows_s"),
        "retained_duration_before_matching_s": primary.get("retained_duration_before_matching_s"),
        "guard_excluded_duration_s": primary.get("guard_excluded_duration_s"),
        "derivative_boundary_excluded_duration_s": primary.get("derivative_boundary_excluded_duration_s"),
        "cutoff_s": primary["end_time_exclusive_s"],
        "mode": primary["mode"],
        "table_percent_definition": "100 * (smooth - shifted) / smooth; positive means lower recorded value",
        "matching_rule": report["matching_rule"],
        "selected_sample_counts": primary["selected_sample_counts"],
        "excluded_sample_counts": primary["excluded_sample_counts"],
        "effective_exposure_s": primary["effective_exposure_s"],
        "command_bins": [cell["command_bin"] for cell in primary["command_bins"]],
        "limitations": report["limitations"],
    }, indent=2), encoding="utf-8")
    print(f"Exported {len(METRICS)} metrics from {len(primary['command_bins'])} command bins; "
          f"equalized exposure {primary['effective_exposure_s'][0]:.6f} s per session.")


if __name__ == "__main__":
    main()
